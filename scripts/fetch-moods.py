"""Fetch official Wazer mood icons from the Waze Community Brand Refresh page
and embed 16 compact square PNG data URIs into src/assets/moods.ts.
"""

from __future__ import annotations

import base64
import os
import re
import struct
import urllib.request

MOODS_URL = "https://sites.google.com/view/social-media-community/graphic-assets/after-brand-refresh/moods"
TARGET_COUNT = 16


def fetch_bytes(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=20) as resp:
        return resp.read()


def png_dimensions(data: bytes) -> tuple[int, int] | None:
    if len(data) < 26 or data[:8] != b"\x89PNG\r\n\x1a\n":
        return None
    w, h = struct.unpack(">II", data[16:24])
    return (w, h)


def main() -> None:
    html = fetch_bytes(MOODS_URL).decode("utf-8", errors="replace")
    srcs = [
        m.group(1)
        for m in re.finditer(r'<img[^>]+src="([^"]+)"', html)
        if "w16383" not in m.group(1) and "sitesv-images-rt" in m.group(1)
    ]

    # Deduplicate preserving order
    seen: set[str] = set()
    unique_srcs: list[str] = []
    for s in srcs:
        if s not in seen:
            seen.add(s)
            unique_srcs.append(s)

    print(f"Found {len(unique_srcs)} candidate mood URLs")

    candidates: list[tuple[int, bytes, int, int]] = []
    for idx, src in enumerate(unique_srcs):
        resized = re.sub(r"=w\d+$", "=w48", src)
        try:
            raw = fetch_bytes(resized)
        except Exception as exc:
            print(f"Skipping candidate {idx}: {exc}")
            continue
        dims = png_dimensions(raw)
        if not dims:
            continue
        w, h = dims
        if abs(w - h) <= 8 and 1000 <= len(raw) <= 4500:
            candidates.append((idx, raw, w, h))

    if len(candidates) < TARGET_COUNT:
        raise RuntimeError(
            f"Expected at least {TARGET_COUNT} valid square mood PNGs, got {len(candidates)}"
        )

    # Spread evenly across the candidate list for diverse moods
    step = len(candidates) / TARGET_COUNT
    selected = [candidates[int(i * step)] for i in range(TARGET_COUNT)]

    uris: list[str] = []
    total_bytes = 0
    for idx, raw, w, h in selected:
        b64 = base64.b64encode(raw).decode("ascii")
        uris.append(f"data:image/png;base64,{b64}")
        total_bytes += len(raw)
        print(f"Selected mood #{idx:02d}: {w}x{h}, {len(raw)} bytes")

    out_dir = os.path.join(os.path.dirname(os.path.dirname(__file__)), "src", "assets")
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "moods.ts")

    lines = [
        "// Auto-generated by scripts/fetch-moods.py from official Waze Moods graphic assets.",
        "// Embedded as compact 48px PNG data URIs so canvas rendering is CORS-safe and self-contained.",
        "",
        "export const WAZER_MOOD_URIS: readonly string[] = [",
    ]
    for uri in uris:
        lines.append(f'    "{uri}",')
    lines.extend(
        [
            "];",
            "",
            "export function preloadMoodSprites(): HTMLImageElement[] {",
            '    if (typeof Image === "undefined") return [];',
            "    return WAZER_MOOD_URIS.map((uri) => {",
            "        const img = new Image();",
            "        img.decoding = \"async\";",
            "        img.src = uri;",
            "        return img;",
            "    });",
            "}",
            "",
        ]
    )

    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))

    print(f"Wrote {out_path} ({len(uris)} icons, {total_bytes} raw PNG bytes)")


if __name__ == "__main__":
    main()
